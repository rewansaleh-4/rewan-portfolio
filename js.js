const root = document.documentElement;
const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");
const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
let currentLang = root.lang === "ckb" ? "ckb" : "en";

function store(key, value) { try { localStorage.setItem(key, value); } catch (e) {} }

// ---------- Language ----------
function applyLanguage(lang) {
  currentLang = lang;
  const t = I18N[lang];
  root.lang = lang;
  root.dir = lang === "ckb" ? "rtl" : "ltr";
  document.title = t.title;
  document.querySelector('meta[name="description"]').setAttribute("content", t.meta);
  const year = new Date().getFullYear();

  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t[el.dataset.i18n].replace("{year}", year);
  });
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    el.innerHTML = t[el.dataset.i18nHtml];
  });

  langToggle.textContent = t.lang_btn;
  langToggle.setAttribute("aria-label", t.aria_lang);
  updateMenuLabel();
  updateThemeLabel();
  store("rs-lang", lang);
}

// ---------- Theme ----------
function applyTheme(theme) {
  root.setAttribute("data-theme", theme);
  updateThemeLabel();
  store("rs-theme", theme);
}
function updateThemeLabel() {
  const t = I18N[currentLang];
  const dark = root.getAttribute("data-theme") !== "light";
  themeToggle.setAttribute("aria-label", dark ? t.aria_to_light : t.aria_to_dark);
}

langToggle.addEventListener("click", () => applyLanguage(currentLang === "en" ? "ckb" : "en"));
themeToggle.addEventListener("click", () => {
  applyTheme(root.getAttribute("data-theme") === "light" ? "dark" : "light");
});

// ---------- Mobile navigation ----------
function updateMenuLabel() {
  menuToggle.setAttribute("aria-label", I18N[currentLang].aria_menu);
}
menuToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.textContent = isOpen ? "×" : "☰";
});
navLinks.querySelectorAll("a").forEach(link => {
  link.addEventListener("click", () => {
    navLinks.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.textContent = "☰";
  });
});

// ---------- Reveal on scroll ----------
const observer = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      observer.unobserve(entry.target);
    }
  });
}, { threshold: 0.12 });
document.querySelectorAll(".reveal").forEach(element => observer.observe(element));

// ---------- Init ----------
applyLanguage(currentLang);